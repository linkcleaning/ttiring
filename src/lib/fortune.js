export const josa = (word, pair) => {
  const c = word.charCodeAt(word.length - 1);
  const has = c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
  const [a, b] = pair.split('/');
  return word + (has ? a : b);
};
export const tier = (s) => (s >= 70 ? 'high' : s >= 48 ? 'mid' : 'low');

export function gradeOf(score) {
  if (score >= 85) return { label: '대길', hanja: '大吉' };
  if (score >= 72) return { label: '길', hanja: '吉' };
  if (score >= 58) return { label: '소길', hanja: '小吉' };
  if (score >= 44) return { label: '평', hanja: '平' };
  return { label: '조심', hanja: '愼' };
}

