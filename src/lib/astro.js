const RAD = Math.PI / 180;
const DAY = 86400000;
const mod = (n, m) => ((n % m) + m) % m;

// 지구 자전 보정(ΔT, 초) 근사
function deltaT(year) {
  if (year < 1955) return 30;
  if (year < 1975) return 33 + (year - 1955) * 0.6;
  if (year < 2000) return 45 + (year - 1975) * 0.75;
  if (year < 2030) return 64 + (year - 2000) * 0.25;
  return 72;
}

