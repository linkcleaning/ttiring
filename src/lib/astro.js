/** UTC 밀리초 → 태양의 겉보기 황경(도) */
export function sunLongitude(utcMs) {
  const y = new Date(utcMs).getUTCFullYear();
  const jde = utcMs / DAY + 2440587.5 + deltaT(y) / 86400;
  const tau = (jde - 2451545.0) / 365250;
  let L = 0;
  VSOP_L.forEach((series, k) => {
    let sum = 0;
    for (const [A, B, C] of series) sum += A * Math.cos(B + C * tau);
    L += sum * tau ** k;
  });
  L = L / 1e8 / RAD + 180; // 지구 → 태양 지심 황경
  const T = tau * 10;
  L += -0.09033 / 3600; // FK5 보정
  const omega = (125.04452 - 1934.136261 * T) * RAD;
  const Ls = (280.4665 + 36000.7698 * T) * RAD;
  const Lm = (218.3165 + 481267.8813 * T) * RAD;
  const dpsi = -17.2 * Math.sin(omega) - 1.32 * Math.sin(2 * Ls) - 0.23 * Math.sin(2 * Lm) + 0.21 * Math.sin(2 * omega);
  L += dpsi / 3600 - 20.4898 / 3600; // 장동 + 광행차
  return mod(L, 360);
}

/** 태양 황경이 target(도)이 되는 시각 (guess 근처에서 뉴턴법) */
export function timeOfLongitude(target, guessMs) {
  let t = guessMs;
  for (let i = 0; i < 12; i++) {
    let diff = mod(target - sunLongitude(t) + 180, 360) - 180;
    t += (diff / 0.98565) * DAY;
    if (Math.abs(diff) < 1e-6) break;
  }
  return t;
}

/** 절(節): 황경 15°+30°k. 월지 = 축(丑)이 소한(285°)부터 */
export function monthBranchAt(utcMs) {
  const lon = sunLongitude(utcMs);
  return mod(1 + Math.floor(mod(lon - 285, 360) / 30), 12);
}

/** 해당 시각 직전/직후 절입 시각 */
export function jeolAround(utcMs) {
  const lon = sunLongitude(utcMs);
  const prevTarget = mod(Math.floor((lon - 15) / 30) * 30 + 15, 360);
  const nextTarget = mod(prevTarget + 30, 360);
  const prev = timeOfLongitude(prevTarget, utcMs - (mod(lon - prevTarget, 360) / 0.98565) * DAY);
  const next = timeOfLongitude(nextTarget, utcMs + (mod(nextTarget - lon, 360) / 0.98565) * DAY);
  return { prev, next };
}

/** 그해 입춘(315°) 시각 */
export function ipchun(year) {
  return timeOfLongitude(315, Date.UTC(year, 1, 4, 0));
}

