export function eventOf(r) {
  const cat = Object.fromEntries(r.categories.map((c) => [c.key, c.score]));
  if (r.rel.includes('충') || (r.rels?.day || []).includes('충')) return 'clash';
  if (cat.재물 >= 92) return 'money';
  if (['천귀성', '천복성'].includes(r.star.name) && r.scores.total >= 72) return 'star';
  if (cat.애정 >= 86) return 'love';
  if (r.rel.includes('원진')) return 'grudge';
  return null;
}

