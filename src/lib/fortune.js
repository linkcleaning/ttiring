/** 날마다 바뀌는 긴 풀이 (3문단) */
function buildDetail(r, rng, grade, luckyHour, bestCat, worstCat) {
  const animal = ANIMALS[r.zodiac];
  const todayGzKo = `${STEMS_KO[r.today.stem]}${BRANCHES_KO[r.today.branch]}`;
  const todayGz = `${STEMS[r.today.stem]}${BRANCHES[r.today.branch]}`;
  const t = tier(r.scores.total);
  const relKey = ['충', '원진', '삼합', '육합', '해', '동기'].find((k) => r.rel.includes(k));
  const dow = new Date(r.today.y, r.today.m - 1, r.today.d).getDay();

  // 오늘 천간·지지가 나에게 필요한 기운인지
  const stemEl = r.today.stem >> 1;
  const branchEl = BRANCH_EL[r.today.branch];
  const fv = (el) => r.analysis.fav[el];
  const elLine = (() => {
    const a = fv(stemEl);
    const b = fv(branchEl);
    if (a >= 0.4 && b >= 0.4) return `오늘 들어온 ${EL_NAME[stemEl]}과 ${EL_NAME[branchEl]} 기운이 둘 다 내게 필요한 쪽이라, 위아래가 모두 나를 돕는 보기 드문 날이에요.`;
    if (a <= -0.4 && b <= -0.4) return `오늘은 하늘의 ${EL_NAME[stemEl]}도 땅의 ${EL_NAME[branchEl]}도 내게는 부담이 되는 기운이라, 평소라면 넘어갈 일이 오늘따라 크게 느껴질 수 있어요.`;
    if (a >= 0.4) return `오늘 하늘로 들어온 ${EL_NAME[stemEl]} 기운이 내게 꼭 필요한 쪽이라, 겉으로 드러나는 일부터 먼저 풀려요.`;
    if (b >= 0.4) return `오늘 땅에 깔린 ${EL_NAME[branchEl]} 기운이 내게 꼭 필요한 쪽이라, 티는 안 나도 속에서부터 받쳐 주는 날이에요.`;
    if (a <= -0.4) return `오늘 하늘로 들어온 ${EL_NAME[stemEl]} 기운이 내게는 부담이 되는 쪽이라, 남의 말에 평소보다 쉽게 흔들려요.`;
    if (b <= -0.4) return `오늘 땅에 깔린 ${EL_NAME[branchEl]} 기운이 내게는 부담이 되는 쪽이라, 몸이 먼저 피로를 알려 줄 수 있어요.`;
    return `오늘 들어온 ${EL_NAME[stemEl]} 기운은 내게 크게 좋지도 나쁘지도 않아요. 그래서 오늘은 날보다 내 선택이 결과를 더 많이 가릅니다.`;
  })();

  const p1 = [
    pick(rng, DAY_OPEN[grade.label]),
    `${todayGzKo}(${todayGz})일인 오늘, 총운은 ${r.scores.total}점 ${grade.label}(${grade.hanja})이에요.`,
    pick(rng, GOD_LONG[r.god][t]),
    WEEK_FLAVOR[dow],
  ].join(' ');

  const p2 = [
    elLine,
    STAGE_LONG[r.stage],
    relKey ? REL_LONG[relKey](animal, `${todayGzKo}(${todayGz})`) : '',
    `당사주로는 ${r.star.name}(${r.star.hanja})이 비추는 날이에요. ${r.star.desc}. 주역으로 뽑은 오늘의 괘는 ${r.iching.changed.ko}(${r.iching.changed.hanja}), 한마디로 '${r.iching.changed.keyword}'의 괘예요.`,
  ].filter(Boolean).join(' ');

  const p3 = [
    `오늘 가장 잘 풀리는 쪽은 ${CAT_LABEL[bestCat.key]}(${bestCat.score}점)이고, 가장 조심할 쪽은 ${CAT_LABEL[worstCat.key]}(${worstCat.score}점)이에요.`,
    `중요한 이야기나 연락은 ${luckyHour.label}(${luckyHour.range}) 사이에 하면 가장 매끄러워요.`,
    pick(rng, DAY_CLOSE[t]),
  ].join(' ');

  return [p1, p2, p3];
}

