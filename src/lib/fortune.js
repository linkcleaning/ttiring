export function eventOf(r) {
  const cat = Object.fromEntries(r.categories.map((c) => [c.key, c.score]));
  if (r.rel.includes('충') || (r.rels?.day || []).includes('충')) return 'clash';
  if (cat.재물 >= 92) return 'money';
  if (['천귀성', '천복성'].includes(r.star.name) && r.scores.total >= 72) return 'star';
  if (cat.애정 >= 86) return 'love';
  if (r.rel.includes('원진')) return 'grudge';
  return null;
}

const EL_NAME = ['목(木)', '화(火)', '토(土)', '금(金)', '수(水)'];
function favLine(r) {
  const el = r.today.stem >> 1; // 오늘 천간의 오행
  const f = r.analysis.fav[el];
  if (f >= 0.4) return `게다가 오늘 들어온 ${EL_NAME[el]} 기운이 나에게 필요한 기운이라 더 잘 풀려요.`;
  if (f <= -0.4) return `다만 오늘 들어온 ${EL_NAME[el]} 기운이 나에게 부담되는 쪽이라 욕심은 줄이는 게 좋아요.`;
  return `오늘 들어온 ${EL_NAME[el]} 기운은 나에게 크게 치우치지 않아요.`;
}

/** 계산 결과 → 화면용 운세 */
export function buildReading(r, concerns = []) {
  const rng = seededRandom(`${r.seed}-text`);
  const animal = ANIMALS[r.zodiac];
  const todayGz = `${STEMS[r.today.stem]}${BRANCHES[r.today.branch]}`;
  const todayGzKo = `${STEMS_KO[r.today.stem]}${BRANCHES_KO[r.today.branch]}`;
  const grade = gradeOf(r.scores.total);

  const relKey = ['충', '원진', '삼합', '육합', '해', '동기'].find((k) => r.rel.includes(k));
  const empathy = [
    ELEMENT_TRAIT[r.selfEl],
    ...pickN(rng, BARNUM, 2),
    GOD_CONTEXT[r.god],
    relKey ? REL_TEXT[relKey](animal, `${todayGzKo}(${todayGz})`) : '',
  ].filter(Boolean).join(' ');

  const { base, changed } = r.iching;
  const headline =
    `오늘의 괘는 ${changed.ko}(${changed.hanja}), '${changed.keyword}'의 괘예요. ${changed.msg}. ` +
    `당사주로 보면 오늘은 ${r.star.name}(${r.star.hanja})의 날이에요. ${r.star.desc}.`;

  const items = r.categories.map((c) => ({
    ...c,
    text: pick(rng, CAT_TEXT[c.key][tier(c.score)]),
    reason: `${CAT_REASON[c.key][r.god]} ${favLine(r)}`,
    tip: CAT_TIP[c.key][tier(c.score)],
  }));

  const supportEl = ['관성', '재성', '식상'].includes(r.god) ? mod(r.selfEl - 1, 5) : mod(r.selfEl + 1, 5);
  const luck = LUCK_BY_EL[supportEl];
  const friends = [[1, 0, 11, 10, 9, 8, 7, 6, 5, 4, 3, 2][r.zodiac], mod(r.zodiac + 4, 12), mod(r.zodiac + 8, 12)];
  const luckyHour = HOURS[friends.find((b) => b >= 4 && b <= 10) ?? friends[0]];
  const clashAnimal = ANIMALS[mod(r.zodiac + 6, 12)];
  const weakest = [...items].sort((a, b) => a.score - b.score)[0];
  const avoid = [
    pick(rng, AVOID_BY_CAT[weakest.key]),
    `${clashAnimal}띠와의 언쟁`,
    r.rel.includes('충') ? `${HOURS[r.today.branch].label}의 중요한 결정` : pick(rng, ['남의 일에 끼어들기', '밤늦은 충동 연락', '빈속에 커피']),
  ];
  const lucky = {
    color: luck.color,
    colorHex: luck.hex,
    number: pick(rng, luck.numbers) + (rng() < 0.5 ? 0 : 10 * (1 + Math.floor(rng() * 3))),
    direction: luck.dir,
    item: pick(rng, luck.items),
    food: luck.food,
    time: `${luckyHour.label} (${luckyHour.range})`,
  };
  const catLabel = { 재물: '금전운', 애정: '연애운', 건강: '건강운', 사업: '커리어운' }[weakest.key];
  const caution =
    `오늘 가장 조심할 건 ${catLabel}이에요. ${josa(avoid[0], '은/는')} 오늘 하루만 멀리하세요. ` +
    `행운은 ${luck.color} 계열에서 와요. ${josa(lucky.item, '을/를')} 곁에 두고, ${lucky.time}에 중요한 연락을 하면 순조로워요.`;

  const catScore = Object.fromEntries(r.categories.map((c) => [c.key, c.score]));
  const concernTips = concerns
    .map((k) => CONCERNS.find((c) => c.key === k))
    .filter(Boolean)
    .map((c) => ({ key: c.key, score: catScore[c.cat], text: CONCERN_TEXT[c.key][tier(catScore[c.cat])] }));

  const tp = r.today.pillars;
  const gzKo = (p) => `${STEMS_KO[p.stem]}${BRANCHES_KO[p.branch]}`;
  const dow = WEEK[new Date(r.today.y, r.today.m - 1, r.today.d).getDay()];

  return {
    grade,
    summary: SUMMARY[r.god][tier(r.scores.total)],
    godLabel: `${r.god}(${GOD_HANJA[r.god]})`,
    dateLine: `${r.today.y}년 ${r.today.m}월 ${r.today.d}일 ${dow}요일`,
    ganzhiLine: `${gzKo(tp.year)}년 ${gzKo(tp.month)}월 ${gzKo(tp.day)}일`,
    zodiacName: `${STEM_COLOR[r.pillars.year.stem]} ${animal}`,
    ilju: `${gzKo(r.pillars.day)}일주`,
    animal,
    empathy,
    headline,
    items,
    avoid,
    lucky,
    caution,
    concernTips,
    event: eventOf(r),
    hexagram: { base, changed, moving: r.iching.movingLine },
  };
}

export function shareText(r, reading) {
  const label = { 재물: '금전', 애정: '연애', 건강: '건강', 사업: '커리어' };
  const cats = reading.items.map((i) => `${label[i.key]} ${i.score}`).join(', ');
  return `띠링! ${reading.dateLine} 내 운세\n총운 ${r.scores.total}점 (${reading.grade.label})\n${reading.summary}\n${cats}\n행운의 컬러 ${reading.lucky.color}, 행운의 숫자 ${reading.lucky.number}`;
}
